function makeStory({
  uid,
  category,
  eyebrow,
  title,
  text = '',
  cta = 'Read More',
  imageAlt = '',
  tags = [],
}) {
  const image = MEDIA_ID_OVERRIDES[uid] || `story-${uid}`;
  const cleanCta = cta.trim();
  return {
    id: uid,
    uid,
    category,
    eyebrow,
    title,
    text,
    href: `https://www.thorindustries.com/stories/${uid}`,
    action: cleanCta,
    cta: cleanCta,
    image,
    mediaId: image,
    imageAlt: imageAlt || title,
    tags,
  };
}

